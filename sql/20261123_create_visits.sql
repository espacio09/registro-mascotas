CREATE TABLE IF NOT EXISTS visits (
  visit_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  pet_id INTEGER NOT NULL REFERENCES pets(pet_id),
  visit_date TIMESTAMPTZ NOT NULL,
  reason TEXT NOT NULL,
  diagnosis TEXT,
  treatment TEXT,
  medication TEXT,
  notes TEXT,
  vet_id INTEGER REFERENCES veterinarians(vet_id) ON DELETE SET NULL,
  symptoms TEXT,
  status VARCHAR(20),
  appointment_id INTEGER REFERENCES appointments(appointment_id)
    ON DELETE SET NULL,
  owner_id BIGINT,
  billing_id INTEGER,
  indication TEXT
);

ALTER TABLE visits
  ADD COLUMN IF NOT EXISTS medication TEXT,
  ADD COLUMN IF NOT EXISTS billing_id INTEGER,
  ADD COLUMN IF NOT EXISTS indication TEXT;

-- Preserve existing visit dates as midnight in the database's configured time zone.
ALTER TABLE visits
  ALTER COLUMN visit_date TYPE TIMESTAMPTZ
  USING visit_date::timestamp AT TIME ZONE current_setting('TimeZone');

DO $$
BEGIN
  IF NOT EXISTS (
    SELECT 1
    FROM pg_constraint
    WHERE conname = 'visits_appointment_id_fkey'
      AND conrelid = 'visits'::regclass
  ) THEN
    ALTER TABLE visits
      ADD CONSTRAINT visits_appointment_id_fkey
      FOREIGN KEY (appointment_id)
      REFERENCES appointments(appointment_id)
      ON DELETE SET NULL
      NOT VALID;
  END IF;
END $$;

CREATE INDEX IF NOT EXISTS visits_appointment_id_idx
  ON visits (appointment_id);
