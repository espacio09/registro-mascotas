CREATE TABLE IF NOT EXISTS billings (
  billing_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  visit_id INTEGER NOT NULL UNIQUE REFERENCES visits(visit_id) ON DELETE CASCADE,
  billing_status VARCHAR(30) NOT NULL DEFAULT 'OPEN',
  CONSTRAINT billings_billing_status_check
    CHECK (billing_status IN ('OPEN', 'IN_PROGRESS', 'COMPLETED'))
);

INSERT INTO billings (visit_id, billing_status)
SELECT visits.visit_id, 'OPEN'
FROM visits
WHERE NOT EXISTS (
  SELECT 1
  FROM billings
  WHERE billings.visit_id = visits.visit_id
);

UPDATE visits
SET billing_id = billings.billing_id
FROM billings
WHERE billings.visit_id = visits.visit_id
  AND visits.billing_id IS NULL;
