CREATE TABLE IF NOT EXISTS appointments (
  appointment_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  pet_id INTEGER NOT NULL REFERENCES pets(pet_id) ON DELETE CASCADE,
  vet_id INTEGER NOT NULL REFERENCES veterinarians(vet_id) ON DELETE RESTRICT,
  appointment_date TIMESTAMPTZ NOT NULL,
  reason TEXT NOT NULL CHECK (BTRIM(reason) <> ''),
  status VARCHAR(20) NOT NULL
    CHECK (status IN ('SCHEDULED', 'COMPLETED', 'CANCELLED'))
);

CREATE INDEX IF NOT EXISTS appointments_pet_date_idx
  ON appointments (pet_id, appointment_date);
